_DIACRITICS = re.compile(r"[\u064B-\u0652\u0640]")


def normalize_arabic(text):
    """توحيد الحروف العربية عشان المقارنة تبقى مرنة."""
    t = (text or "").lower()
    t = _DIACRITICS.sub("", t)
    for a in "أإآ":
        t = t.replace(a, "ا")
    t = t.replace("ة", "ه").replace("ى", "ي").replace("ؤ", "و").replace("ئ", "ي")
    return t


def keyword_present(keyword, answer):
    """بترجع True لو الكلمة (إنجليزي) أو أي مرادف عربي ليها موجود في الإجابة."""
    ans_en = (answer or "").lower()
    if keyword.lower() in ans_en:
        return True
    ans_ar = normalize_arabic(answer)
    for syn in SYNONYMS.get(keyword.lower(), []):
        if normalize_arabic(syn) in ans_ar:
            return True
    return False
